#!/usr/bin/env python3
"""Copy an HTML tool into the public collection, update catalog, and rebuild."""
from pathlib import Path
import argparse,json,re,shutil
from build_site import ROOT,catalog,build
p=argparse.ArgumentParser(description=__doc__)
p.add_argument('source',type=Path,help='A standalone HTML file, or directory containing index.html and local assets')
p.add_argument('--id',required=True,help='Unique lowercase slug')
p.add_argument('--title',required=True)
p.add_argument('--description',required=True)
p.add_argument('--category',default='Learning')
p.add_argument('--level',default='All learners')
a=p.parse_args()
if not re.fullmatch(r'[a-z][a-z0-9-]{0,59}',a.id):p.error('Use a lowercase slug, starting with a letter.')
source=a.source.resolve(); entries=catalog();target=ROOT/'tools'/a.id
if any(t['id']==a.id for t in entries) or target.exists():p.error('That ID already exists. Edit its existing files to update it.')
if not source.exists() or source.is_symlink():p.error('Source must be a real file or directory.')
if source.is_dir():
 if not (source/'index.html').is_file():p.error('Directory must contain index.html.')
 if any(v.is_symlink() for v in source.rglob('*')):p.error('Tool directories may not contain symlinks.')
 if ROOT.resolve().is_relative_to(source) or source.is_relative_to((ROOT/'tools').resolve()):p.error('Choose an external source directory to avoid copying the project into itself.')
 shutil.copytree(source,target,ignore=shutil.ignore_patterns('.git','.env','.env.*','node_modules','__pycache__','*.pyc'))
else:
 if source.suffix.lower() not in ['.html','.htm']:p.error('Choose an HTML file.')
 target.mkdir(parents=True);shutil.copy2(source,target/'index.html')
entries.append({'id':a.id,'title':a.title,'subtitle':'Interactive learning tool','category':a.category,'level':a.level,'description':a.description,'path':f'tools/{a.id}/index.html','tags':['HTML tool'],'version':'1.0.0'})
(ROOT/'site-assets/catalog.js').write_text('/* Public catalog. Generated by scripts/add_tool.py. */\nwindow.TOOL_CATALOG = '+json.dumps(entries,ensure_ascii=False,indent=2)+';\n')
build()
print('Added tool locally. Publish the site to make it available to everyone.')
